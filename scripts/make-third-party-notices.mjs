// Generates THIRD_PARTY_NOTICES.md from the installed dependency tree: name, version, license id,
// homepage and the license text shipped by each package, for everything that is compiled into the
// APK (the shell's package.json `dependencies`) or into the game page (Babylon.js, idb), plus the
// status of the bundled non-code assets. Licence ids come from each package's own package.json:
// nothing is guessed. Run after `npm ci`:  node scripts/make-third-party-notices.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BUNDLED_IN_PAGE = ['@babylonjs/core', 'idb'];     // imported by src/ and inlined into the page by Vite

export function collect(read = (p) => readFileSync(p, 'utf8'), exists = existsSync, list = readdirSync) {
  const pkg = JSON.parse(read('package.json'));
  const names = [...new Set([...Object.keys(pkg.dependencies ?? {}), ...BUNDLED_IN_PAGE])].sort();
  return names.map((name) => {
    const dir = `node_modules/${name}`;
    const meta = JSON.parse(read(`${dir}/package.json`));
    const licenseFile = list(dir).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
    return {
      name, version: meta.version,
      license: typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? null),
      homepage: meta.homepage ?? (typeof meta.repository === 'string' ? meta.repository : meta.repository?.url ?? null),
      text: licenseFile && exists(`${dir}/${licenseFile}`) ? read(`${dir}/${licenseFile}`).trim() : null,
    };
  });
}

export function render(rows) {
  const out = [
    '# Third-party notices', '',
    "Where's the Bottom? (Hot Attic Games). Generated by `scripts/make-third-party-notices.mjs` from the installed dependency tree; do not edit by hand.", '',
    '## Code compiled into the app', '',
    '| Package | Version | License |', '| --- | --- | --- |',
    ...rows.map(r => `| ${r.name} | ${r.version} | ${r.license ?? '**UNKNOWN: needs review**'} |`), '',
    'Transitive dependencies of the Expo / React Native shell carry their own licenses (MIT, Apache-2.0 and similar); list them with `npm ls --all --prod` and `npx license-checker` before a store submission.', '',
    '## Bundled non-code assets (status as recorded in this repository)', '',
    '| Asset | Status |', '| --- | --- |',
    '| Fonts: Fredoka, Lilita One (`src/assets/fonts`) | SIL OFL 1.1: license texts are in the repository (`OFL-*.txt`); not yet shown inside the app |',
    '| Models: Kenney packs (`src/assets` characters, ramps, props) | Kenney publishes these as CC0; the source and license are not recorded in the repository: needs owner confirmation |',
    '| Models: rocks, flowers, props (`*.stl`) | Provenance unknown: needs owner confirmation |',
    '| Music: three MP3 tracks (`src/assets/music`) | ID3 comment "made with suno"; license/plan not documented: needs owner confirmation before commercial release |',
    '| Menu art, splash art, gear icon | Described only as "supplied": needs owner confirmation |',
    '| Hot Attic Games logo (`Hot_Attic_Games_Master_Logo_ALPHA_FINAL.png`) | Studio-owned artwork |',
    '| Controller glyph library, "Input Prompts" by JulioCacko (`Source.zip`) | Not shipped in this app. License identified as CC0 1.0 Universal (asset) / MIT (code) from the owner-supplied store-page screenshot (Unity Asset Store listing, published 2023-06-30, updated 2025-02-03; "no generative AI used"); not independently verified against the source, and the archive itself contains no license file |', '',
    '## License texts', '',
  ];
  for (const r of rows) out.push(`### ${r.name} ${r.version} (${r.license ?? 'unknown'})`, '', r.homepage ? `Source: ${r.homepage}` : '', '', r.text ? '```text\n' + r.text + '\n```' : '_No license file shipped in the package; see the license id above._', '');
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(collect());
  if (process.argv.includes('--check')) {
    if (!existsSync('THIRD_PARTY_NOTICES.md') || readFileSync('THIRD_PARTY_NOTICES.md', 'utf8') !== text) { console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/make-third-party-notices.mjs'); process.exit(1); }
    console.log('THIRD_PARTY_NOTICES.md is up to date');
  } else { writeFileSync('THIRD_PARTY_NOTICES.md', text); console.log(`THIRD_PARTY_NOTICES.md: ${collect().length} packages`); }
}
